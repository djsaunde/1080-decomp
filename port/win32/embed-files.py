#!/usr/bin/env python3
"""Build step of the Windows port (plan section 27): libultraship's shader files as C++ initialisers.

    embed-files.py <base dir> <out.inc> <relative path>...

Each <relative path> under <base dir> becomes `{"<relative path>", "<bytes>", <size>},` (the entries of
ship_shim.cpp's kShaders[]), so the executable needs no libultraship checkout at run time.
"""
import os
import sys


def main():
    base, out, rels = sys.argv[1], sys.argv[2], sys.argv[3:]
    lines = ["/* generated by port/win32/embed-files.py -- do not edit */"]
    for rel in rels:
        data = open(os.path.join(base, rel), "rb").read()
        lit = "".join("\\x%02x" % b for b in data)
        chunks = [lit[i:i + 160] for i in range(0, len(lit), 160)] or [""]
        lines.append('{"%s",' % rel)
        lines += ['"%s"' % c for c in chunks]
        lines.append(", %d}," % len(data))
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
