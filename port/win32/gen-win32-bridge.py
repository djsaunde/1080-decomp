#!/usr/bin/env python3
"""Link step of the Windows port (plan section 29): the symbol bridge between the game and the toolchain.

    gen-win32-bridge.py --nm NM --aliases port/gen/aliases.ld -o bridge.ld GAME... --host HOST...

The game side (the game library, port/uso, port/ultra, port/audio and the port host's C units: GAME, archives
or objects) is compiled with -fno-leading-underscore, so its symbols keep the ELF spelling the rest of the port
relies on (`__asm__("name")` labels in include/uso_call.h, port/gen/aliases.ld, cc-select.py's binds). Every
other object of the executable (the mingw CRT, libgcc, libstdc++, SDL2, the Win32 import libraries and the
native host's C++, HOST) has the usual i386 Windows spelling with a leading `_`. bridge.ld is an implicit
linker script that joins the two:

  X = _X;  EXTERN(_X)            for each symbol the game side references and does not define (memcpy,
                                 __udivdi3, port_native_open, ...); a dllimport pointer __imp_X maps to
                                 __imp__X
  _X = X;                        for each symbol a HOST object references as _X that the game side defines
                                 as X (main for the CRT, the port_fb_* calls of the C++ host)

Only symbols some library defines are bridged (--cc: the toolchain's libraries, found with -print-file-name).
A game reference that nothing defines is, on Linux, held only by code --gc-sections drops (the renamed dead
placeholder copies: the Linux link has 0 undefined symbols, port/undefined.txt). PE ld reports undefined
references before it collects sections, so --traps writes a C file that defines each of them as an aborting
trap ("PORT TRAP: <name>"), the Linux build's PORT_TRAP_UNDEFINED in miniature: nothing live reaches one. Weak undefined references are
left alone (they stay 0 when nothing defines them, as on Linux). A game-side name `_X` whose bridge target `__X`
would collide with the target `_X` of a game reference `X` is an error (the game side must not use both
`exit` and `_exit`, say).
"""
import argparse
import os
import re
import subprocess
import sys

DEFINED = set("TDBRCVWGSAI")
TOOLCHAIN_LIBS = ["mingw32", "gcc", "gcc_eh", "moldname", "mingwex", "msvcrt", "pthread", "stdc++", "kernel32",
                  "user32", "advapi32", "shell32", "comdlg32", "winmm", "gdi32", "opengl32", "ole32"]


def toolchain_archives(cc):
    paths = []
    for lib in TOOLCHAIN_LIBS:
        p = subprocess.run([cc, "-print-file-name=lib%s.a" % lib], capture_output=True, text=True).stdout.strip()
        if os.path.isabs(p) and os.path.exists(p):
            paths.append(p)
    return paths


def nm_symbols(nm, paths):
    """-> (defined, undefined) symbol name sets of the given archives / objects"""
    defined, undefined = set(), set()
    if not paths:
        return defined, undefined
    out = subprocess.run([nm, "-g", "--no-sort"] + list(paths), capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == "U":
            undefined.add(parts[1])
        elif len(parts) == 3 and parts[1] in DEFINED:
            defined.add(parts[2])
    return defined, undefined


def alias_lhs(path):
    names = set()
    for line in open(path):
        m = re.match(r"\s*([\w.$@]+)\s*=", line)
        if m:
            names.add(m.group(1))
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nm", required=True)
    ap.add_argument("--cc", required=True, help="the C compiler (its -print-file-name finds the toolchain libraries)")
    ap.add_argument("--aliases", action="append", default=[])
    ap.add_argument("-o", required=True)
    ap.add_argument("--traps", help="write the trap definitions of the unresolved game references here (C)")
    ap.add_argument("game", nargs="*")
    ap.add_argument("--host", nargs="*", default=[])
    a = ap.parse_args()
    gdef, gundef = nm_symbols(a.nm, a.game)
    hdef, hundef = nm_symbols(a.nm, a.host)
    tdef, _ = nm_symbols(a.nm, toolchain_archives(a.cc))
    avail = hdef | tdef
    adef = set()
    for p in a.aliases:
        adef |= alias_lhs(p)
    lines = ["/* generated by port/win32/gen-win32-bridge.py -- do not edit (plan 29) */"]
    out = []
    targets = {}
    for u in sorted(gundef - gdef - adef):
        tgt = "__imp__" + u[6:] if u.startswith("__imp_") else "_" + u
        if tgt in avail:
            targets[u] = tgt
    clash = sorted(u for u in targets if u in targets.values())
    if clash:
        sys.exit("gen-win32-bridge: the game side references both X and _X for: %s" % " ".join(clash))
    if a.traps:
        weak_or_known = targets.keys() | {"main"}
        unresolved = sorted(u for u in gundef - gdef - adef - weak_or_known - avail)
        t = ["/* generated by port/win32/gen-win32-bridge.py --traps -- do not edit (plan 29): the game's references",
             " * that only Linux's --gc-sections removes; each is an aborting trap */",
             "#include <stdio.h>", "#include <stdlib.h>",
             "static void port_win32_trap(const char *name) {",
             '    fprintf(stderr, "PORT TRAP: %s (a symbol the Linux link drops as dead code)\\n", name);',
             "    fflush(stderr);", "    abort();", "}"]
        for i, u in enumerate(unresolved):
            t.append('void port_win32_trap_%d(void) __asm__("%s");' % (i, u))
            t.append('void port_win32_trap_%d(void) { port_win32_trap("%s"); }' % (i, u))
        with open(a.traps, "w") as fh:
            fh.write("\n".join(t) + "\n")
        print("gen-win32-bridge: %d unresolved game references trapped" % len(unresolved))
    for u, tgt in sorted(targets.items()):
        out.append('EXTERN("%s")' % tgt)
        out.append('"%s" = "%s";' % (u, tgt))
    back = []
    for h in sorted(hundef - hdef):
        if h.startswith("_") and h[1:] in gdef:
            back.append('"%s" = "%s";' % (h, h[1:]))
    if "main" in gdef:
        back.append('"_main" = "main";')
    lines += out + sorted(set(back))
    with open(a.o, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("gen-win32-bridge: %d game -> toolchain, %d toolchain -> game" % (len(out) // 2, len(set(back))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
