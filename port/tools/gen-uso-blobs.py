#!/usr/bin/env python3
"""Build step of the port: the USO data blobs (docs/1080_PC_PORT_PLAN.md section 16.5).

    gen-uso-blobs.py <extracted dir> <port/gen/uso_blobs.tsv> <out.s>

<extracted dir> is the output of port/tools/extract/extract.py run on the user's ROM (its
manifest.json and uso/<file>/NN_<Type>.bin).  For each module section uso_blobs.tsv lists, the
assembly file defines
  port_<mod>_<sec>_init   the section's bytes as on the cartridge (.incbin, read-only), and
  port_<mod>_<sec>        a zeroed writable blob of the same size, which port/uso fills from the
                          _init copy and relocates each time the module "loads";
and port_<mod>_bss for a Bss section.  No ROM bytes are kept in the repository.

Byte order: each Data / RoData section goes through port/tools/blob_swap.py (the typed swap of
port/gen/blob_types.tsv, next to uso_blobs.tsv); the swapped copy is written next to <out.s>.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import blob_swap  # noqa: E402


def main():
    ext, tsv, out = sys.argv[1:4]
    man = json.load(open(os.path.join(ext, "manifest.json")))
    files = {f["name"]: f for f in man["files"]}
    types = os.path.join(os.path.dirname(os.path.abspath(tsv)), "blob_types.tsv")
    swdir = os.path.splitext(os.path.abspath(out))[0] + ".swapped"
    os.makedirs(swdir, exist_ok=True)
    lines = ["/* generated by port/tools/gen-uso-blobs.py from %s -- do not edit */" % ext]
    bad = []
    for line in open(tsv):
        if not line.strip() or line.startswith("#"):
            continue
        short, name, sec, size = line.rstrip("\n").split("\t")
        size = int(size)
        sym = "port_%s_%s" % (short, sec.lower())
        if sec == "Bss":
            lines += ['\t.section .bss.%s,"aw",@nobits' % sym, "\t.globl %s" % sym, "\t.balign 16",
                      "%s:" % sym, "\t.zero %d" % size, "\t.size %s, %d" % (sym, size)]
            continue
        f = files.get(name)
        s = next((s for s in (f or {}).get("sections", []) if s["name"] == sec and s.get("file")), None)
        if s is None or s.get("size") != size:
            bad.append("%s %s: %s" % (name, sec, "missing" if s is None else "size %s, want %d" % (s.get("size"), size)))
            continue
        path = os.path.abspath(os.path.join(ext, s["file"]))
        data, nswap = blob_swap.swap_section(types, short, sec, open(path, "rb").read())
        if nswap:
            path = os.path.abspath(os.path.join(swdir, "%s.bin" % sym))
            with open(path, "wb") as fh:
                fh.write(data)
        lines += ['\t.section .rodata.%s_init,"a"' % sym, "\t.globl %s_init" % sym, "\t.balign 16",
                  "%s_init:" % sym, '\t.incbin "%s"' % path, "\t.size %s_init, %d" % (sym, size),
                  '\t.section .bss.%s,"aw",@nobits' % sym, "\t.globl %s" % sym, "\t.balign 16",
                  "%s:" % sym, "\t.zero %d" % size, "\t.size %s, %d" % (sym, size)]
    if bad:
        sys.exit("gen-uso-blobs: the extracted ROM does not match the build:\n  " + "\n  ".join(bad))
    lines.append('\t.section .note.GNU-stack,"",@progbits')
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
