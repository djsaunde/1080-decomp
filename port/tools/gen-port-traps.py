#!/usr/bin/env python3
"""PORT_TRAP_UNDEFINED (debug only, plan 18.9): one trap per symbol the tenshoe link leaves undefined.

  gen-port-traps.py --probe <probe exe> --out port_traps.c [--nm nm] [--objdump objdump] LIB_OR_OBJ...

The probe is tenshoe linked with --warn-unresolved-symbols.  Its unversioned `U` symbols are the
missing ones (versioned ones are libc / libm).  A symbol called from .text (R_386_PC32 / PLT32 in
the given archives / objects) gets a code trap, every other one a data trap (port/trap/trap.c).
"""
import argparse
import re
import subprocess
import sys

IDENT = re.compile(r"^[A-Za-z_.$][A-Za-z0-9_.$]*$")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--probe", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--nm", default="nm")
    ap.add_argument("--objdump", default="objdump")
    ap.add_argument("inputs", nargs="*")
    a = ap.parse_args()

    out = subprocess.run([a.nm, "-u", a.probe], check=True, capture_output=True, text=True).stdout
    syms = sorted({ln.split()[1] for ln in out.splitlines()
                   if len(ln.split()) == 2 and ln.split()[0] == "U" and "@" not in ln.split()[1]})
    bad = [s for s in syms if not IDENT.match(s)]
    if bad:
        sys.exit("gen-port-traps: unusable symbol names: %s" % bad)

    want = set(syms)
    code = set()
    for inp in a.inputs:
        r = subprocess.run([a.objdump, "-r", inp], capture_output=True, text=True)
        sec = ""
        for ln in r.stdout.splitlines():
            m = re.match(r"RELOCATION RECORDS FOR \[(.*)\]:", ln)
            if m:
                sec = m.group(1)
                continue
            p = ln.split()
            if len(p) == 3 and p[2] in want and p[1] in ("R_386_PC32", "R_386_PLT32") \
                    and sec.startswith(".text"):
                code.add(p[2])
    data = [s for s in syms if s not in code]

    w = []
    w.append("/* generated by port/tools/gen-port-traps.py (PORT_TRAP_UNDEFINED, debug only): %d code"
             " traps, %d data traps.  Do not edit. */" % (len(code), len(data)))
    w.append("extern void port_trap_code(const char *sym) __attribute__((noreturn));")
    for s in sorted(code):
        w.append("void %s(void) { port_trap_code(\"%s\"); }" % (s, s))
    w.append("const unsigned port_trap_data_count = %d;" % len(data))
    w.append("const char *const port_trap_data_names[] = {%s};"
             % ", ".join('"%s"' % s for s in data) if data else
             "const char *const port_trap_data_names[] = {\"(none)\"};")
    # the PROT_NONE region: 2 pages per symbol, the symbol at the start of its second page
    asm = ['    .section .port_trap_data,"aw",@nobits', "    .balign 4096",
           "    .globl port_trap_data_start", "port_trap_data_start:"]
    for s in data:
        asm += ["    .skip 4096", "    .globl %s" % s, "    .type %s,@object" % s, "%s:" % s,
                "    .skip 4096"]
    asm += ["    .globl port_trap_data_end", "port_trap_data_end:", "    .previous"]
    w.append("__asm__(\n%s);" % "\n".join('"%s\\n"' % ln.replace('"', '\\"') for ln in asm))
    with open(a.out, "w") as fh:
        fh.write("\n".join(w) + "\n")
    print("gen-port-traps: %d code, %d data traps -> %s" % (len(code), len(data), a.out))
    for s in sorted(code):
        print("  code %s" % s)
    for s in data:
        print("  data %s" % s)


if __name__ == "__main__":
    main()
