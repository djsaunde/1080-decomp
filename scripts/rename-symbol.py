#!/usr/bin/env python3
"""Rename a function / global symbol across the 1080 repo, ROM-neutrally.

Usage:
  scripts/rename-symbol.py OLD NEW [--dry-run]
  scripts/rename-symbol.py --batch renames.tsv [--dry-run]   # lines: OLD<TAB>NEW [# comment]

What it touches (all whole-word, `[A-Za-z0-9_]` boundaries):
  * every git-tracked TEXT file except episodes/ (historical training records),
    report.json (regenerated by scripts/readability-gate.sh), tools/, assets/;
    that covers src/ C/C++/headers, asm/ .s (glabel/endlabel/jal/nonmatching),
    Makefile (REPLACE_FUNC_BODY, SUFFIX_BYTES_FORCE, POST_COMPILE renames,
    per-file rules), undefined_syms*.txt pins, tenshoe.ld, symbol_addrs.txt,
    scripts/*.json bindings, README / DECOMPILED_FUNCTIONS.md;
  * DERIVED build symbols `OLD_rodata`, `OLD_bss`, `OLD_data`, ... (made by
    replace-function-body.py as func_name + section name, pinned in
    undefined_syms) are renamed to `NEW_<sect>` too;
  * file NAMES whose stem token is OLD (INCLUDE_ASM resolves `<dir>/<NAME>.s`,
    src/match_imports/<NAME>.c, scripts/match-bindings-<NAME>[-nm].json) via git mv;
  * expected/**/*.o symbol tables (objdiff matches target symbols BY NAME):
    OLD, OLD.NON_MATCHING and derived OLD_<sect> are renamed in place with the
    metadata-only strtab repoint of scripts/rename-elf-symbol.py (NOT objcopy,
    which rewrites the symtab and renames local section symbols);
  * appends `OLD<TAB>NEW` to renames.tsv (ledger: docs in the monorepo keep
    using the old placeholder names; grep this file to translate).

Refusals (names never reach the ROM: USO Sym tables carry [tag,value,HASH]
of the ORIGINAL names as ROM data, and the ROM is objcopy -O binary of the
link, so symbol strings are not emitted. The only ways a rename could change
bytes are guarded here):
  * OLD inside a C string literal / .ascii(z) (would change data bytes);
  * OLD appearing mangled (`OLD__F...`, C++ objcopy --redefine-sym maps);
  * OLD is a zero-address sentinel (`*_00000000*`, USO import/base placeholders);
  * NEW not a valid identifier / is a C keyword / already a symbol in any
    expected or build object, undefined_syms, symbol_addrs or tenshoe.ld;
  * NEW already used as a CODE token (comments stripped) in a file that
    contains OLD (two meanings would merge inside one TU, e.g. a local
    `#define osSendMesg gl_func_00000000`);
  * OLD defined in objects of more than one src/<segment>/ (ambiguous).
After a batch, run scripts/readability-gate.sh (full make + ROM cmp +
verify-blocks + non_matching_objects + report diff by address).
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
rfb = __import__("replace-function-body")

ROOT = Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], cwd=HERE, text=True).strip())
DERIVED = ("rodata", "data", "bss", "sdata", "sbss", "text", "lit4", "lit8")
SKIP_PREFIX = ("episodes/", "tools/", "assets/", "expected/", "landwip/")
SKIP_FILES = {"report.json", "renames.tsv"}
C_KEYWORDS = set("""auto break case char const continue default do double else enum extern float for goto
if int long register return short signed sizeof static struct switch typedef union unsigned void volatile
while class new delete this operator template virtual inline""".split())
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def word_re(name):
    return re.compile(r"(?<![A-Za-z0-9_])" + re.escape(name) + r"(?![A-Za-z0-9_])")


def token_re(old):
    # OLD, OLD.NON_MATCHING (via the '.' boundary) and OLD_<derived section>
    return re.compile(r"(?<![A-Za-z0-9_])" + re.escape(old) +
                      r"(_(?:" + "|".join(DERIVED) + r"))?(?![A-Za-z0-9_])")


def tracked_text_files():
    out = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT).split(b"\0")
    files = []
    for b in out:
        p = b.decode()
        if not p or p.startswith(SKIP_PREFIX) or p in SKIP_FILES:
            continue
        fp = ROOT / p
        if fp.is_symlink() or not fp.is_file():
            continue
        files.append(p)
    return files


_text_cache = {}


def read_text(p):
    if p not in _text_cache:
        raw = (ROOT / p).read_bytes()
        _text_cache[p] = None if b"\0" in raw[:8192] else raw.decode("utf-8", errors="surrogateescape")
    return _text_cache[p]


def strip_comments(path, text):
    if path.endswith((".c", ".h", ".cpp", ".inc", ".ld", ".txt", ".s")):
        text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
        if path.endswith((".c", ".h", ".cpp")):
            text = re.sub(r"//[^\n]*", " ", text)
    if path.endswith((".s", ".inc")) or path == "Makefile" or path.endswith((".mk", ".sh", ".py")):
        text = re.sub(r"(?m)#(?!\s*(?:include|define|if|ifdef|ifndef|else|endif|pragma)\b)[^\n]*", " ", text)
    return text


def object_files():
    objs = list((ROOT / "expected").rglob("*.o"))
    if (ROOT / "build").is_dir():
        objs += [p for p in (ROOT / "build").rglob("*.o")]
    return objs


def elf_symbols(path):
    try:
        elf = rfb.Elf(path.read_bytes())
        st = elf.find_section(".symtab")
    except Exception:
        return []
    stt = elf.sections[st][6]
    out = []
    for _idx, f in elf.iter_symtab(st):
        name = elf.strtab_string(stt, f[0])
        if name:
            out.append((name, f[5] != 0))  # (name, defined)
    return out


class Index:
    def __init__(self):
        self.obj_syms = {}  # path -> [(name, defined)]
        for o in object_files():
            self.obj_syms[o] = elf_symbols(o)
        self.linker_names = set()
        for f in list(ROOT.glob("undefined_*.txt")) + [ROOT / "symbol_addrs.txt", ROOT / "tenshoe.ld"]:
            if f.exists():
                for m in re.finditer(r"(?m)^\s*([A-Za-z_][A-Za-z0-9_.]*)\s*=", strip_comments(f.name, f.read_text(errors="replace"))):
                    self.linker_names.add(m.group(1))
        self.all_names = set(self.linker_names)
        for syms in self.obj_syms.values():
            self.all_names.update(n for n, _ in syms)

    def defining_segments(self, name):
        segs = set()
        for o, syms in self.obj_syms.items():
            if any(n == name and d for n, d in syms):
                rel = o.relative_to(ROOT).parts
                # expected/src/<seg>/x.o | build/[non_matching/]src/<seg>/x.o
                if "src" in rel:
                    i = rel.index("src")
                    if i + 1 < len(rel) - 1:
                        segs.add(rel[i + 1])
        return segs


def check(old, new, idx, files, pending_new):
    errs, warns = [], []
    if not IDENT.match(new) or new in C_KEYWORDS:
        errs.append(f"NEW {new!r} is not a valid C identifier")
    if old == new:
        errs.append("OLD == NEW")
    if "00000000" in old:
        errs.append(f"{old} is a zero-address sentinel/placeholder name (USO import/base); never rename")
    if new in idx.all_names or new in pending_new:
        errs.append(f"NEW {new} already exists as a symbol (object/undefined_syms/symbol_addrs/ld/batch)")
    for d in DERIVED:
        if f"{new}_{d}" in idx.all_names:
            errs.append(f"derived NEW {new}_{d} already exists")
    known = old in idx.all_names
    if not known:
        errs.append(f"OLD {old} is not a symbol in any expected/build object or linker-symbol file")
    segs = idx.defining_segments(old)
    if len(segs) > 1:
        errs.append(f"{old} is defined in several segments {sorted(segs)}; rename is ambiguous")
    wr, nr = word_re(old), word_re(new)
    mangled = re.compile(r"(?<![A-Za-z0-9_])" + re.escape(old) + r"__[A-Za-z0-9]")
    strlit = re.compile(r'"(?:[^"\\\n]|\\.)*"')
    hits = []
    for p in files:
        t = read_text(p)
        if t is None or old not in t or not wr.search(t):
            continue
        hits.append(p)
        if mangled.search(t):
            errs.append(f"{p}: {old} appears in a C++-mangled form ({old}__...); handle by hand")
        if p.endswith((".c", ".h", ".cpp")):
            code = strip_comments(p, t)
            for line in code.splitlines():
                if not wr.search(line):
                    continue
                if re.match(r"\s*(#\s*include|#\s*pragma\s+GLOBAL_ASM|INCLUDE_ASM|INCLUDE_RODATA)", line):
                    continue
                for lit in strlit.findall(line):
                    if wr.search(lit):
                        errs.append(f"{p}: {old} inside a string literal (would change data bytes): {line.strip()[:120]}")
        if p.endswith((".s", ".inc")):
            for line in t.splitlines():
                if re.search(r"\.ascii", line) and wr.search(line):
                    errs.append(f"{p}: {old} inside .ascii data: {line.strip()[:120]}")
        code = strip_comments(p, t)
        # NEW=OLD is a post-compile rename spec (donor compiled under its real
        # name, renamed to the placeholder); it becomes a harmless NEW=NEW.
        code = re.sub(r"(?<![A-Za-z0-9_])" + re.escape(new) + "=" + re.escape(old) + r"(?![A-Za-z0-9_])", " ", code)
        # Makefile/linker files: one rule line = one context; C/asm: the whole TU.
        units = code.splitlines() if p in ("Makefile", "tenshoe.ld") or p.endswith(".txt") else [code]
        if any(wr.search(u) and nr.search(u) for u in units):
            errs.append(f"{p}: NEW {new} is already a code token in a file/rule that uses {old}")
    return errs, warns, hits


def plan_file_renames(old, new):
    moves = []
    out = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT).split(b"\0")
    pat = word_re(old)
    for b in out:
        p = b.decode()
        if not p or p.startswith(("episodes/", "expected/")):
            continue
        name = Path(p).name
        stem = name.split(".")[0]
        # whole-token match in the basename, but only when OLD is the stem or a
        # dash-delimited part (match-bindings-OLD-nm.json); never `OLD_pad.s`.
        parts = re.split(r"-", stem)
        if stem == old or old in parts:
            newname = pat.sub(new, name)
            moves.append((p, str(Path(p).with_name(newname))))
    return moves


def apply(renames, dry):
    idx = Index()
    files = tracked_text_files()
    pending = set()
    all_errs = []
    plan = []
    for old, new in renames:
        errs, warns, hits = check(old, new, idx, files, pending)
        pending.add(new)
        if errs:
            all_errs += [f"[{old} -> {new}] {e}" for e in errs]
        plan.append((old, new, hits))
    if all_errs:
        print("REFUSED:\n  " + "\n  ".join(all_errs), file=sys.stderr)
        return 1

    for old, new, hits in plan:
        tr = token_re(old)
        sub = lambda m: new + (m.group(1) or "")
        nfiles = 0
        nrefs = 0
        for p in hits:
            t = read_text(p)
            t2, n = tr.subn(sub, t)
            if n:
                nfiles += 1
                nrefs += n
                if not dry:
                    (ROOT / p).write_text(t2, encoding="utf-8", errors="surrogateescape")
                _text_cache[p] = t2
        # expected/ objects
        specs_by_obj = {}
        for o, syms in idx.obj_syms.items():
            rel = o.relative_to(ROOT)
            if rel.parts[0] != "expected":
                continue
            names = {n for n, _ in syms}
            specs = []
            for cand in [old, old + ".NON_MATCHING"] + [f"{old}_{d}" for d in DERIVED]:
                if cand in names:
                    specs.append(f"{cand}={new}{cand[len(old):]}")
            if specs:
                specs_by_obj[o] = specs
        for o, specs in specs_by_obj.items():
            if not dry:
                subprocess.run([sys.executable, str(HERE / "rename-elf-symbol.py"), str(o)] + specs,
                               check=True, stdout=subprocess.DEVNULL)
        moves = plan_file_renames(old, new)
        for a, b in moves:
            if not dry:
                subprocess.run(["git", "mv", a, b], cwd=ROOT, check=True)
            if a in _text_cache:
                _text_cache[b] = _text_cache.pop(a)
            files = [b if f == a else f for f in files]
        print(f"{'[dry] ' if dry else ''}{old} -> {new}: {nrefs} refs in {nfiles} files, "
              f"{len(specs_by_obj)} expected objs, {len(moves)} file moves")
        for a, b in moves:
            print(f"    mv {a} -> {b}")
        if not dry:
            led = ROOT / "renames.tsv"
            new_ledger = not led.exists()
            with led.open("a") as fh:
                if new_ledger:
                    fh.write("# old\tnew  (ledger of readability renames; docs/ keep the old names)\n")
                fh.write(f"{old}\t{new}\n")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("old", nargs="?")
    ap.add_argument("new", nargs="?")
    ap.add_argument("--batch", type=Path)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    renames = []
    if a.batch:
        for line in a.batch.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                o, n = line.split()[:2]
                renames.append((o, n))
    elif a.old and a.new:
        renames.append((a.old, a.new))
    else:
        ap.error("give OLD NEW or --batch FILE")
    olds = [o for o, _ in renames]
    if len(set(olds)) != len(olds):
        sys.exit("duplicate OLD in batch")
    sys.exit(apply(renames, a.dry_run))


if __name__ == "__main__":
    main()
