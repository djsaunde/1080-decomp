#!/usr/bin/env python3
"""Rename a function / global symbol across the 1080 repo, ROM-neutrally.

Usage:
  scripts/rename-symbol.py OLD NEW [--dry-run]
  scripts/rename-symbol.py --batch renames.tsv [--dry-run]   # lines: OLD<TAB>NEW [# comment]
  add --allow-scoped-alias to tolerate NEW already used in a C file as a
  scoped macro alias (`#define NEW gl_ref_X ... #undef NEW`, the OoT-name
  idiom in game_libs_post.c) provided OLD never occurs inside such a scope.

What it touches (all whole-word, `[A-Za-z0-9_]` boundaries):
  * every git-tracked TEXT file except episodes/ (historical training records),
    report.json (regenerated by scripts/readability-gate.sh), tools/, assets/;
    that covers src/ C/C++/headers, asm/ .s (glabel/endlabel/jal/nonmatching),
    Makefile (REPLACE_FUNC_BODY, SUFFIX_BYTES_FORCE, POST_COMPILE renames,
    per-file rules), undefined_syms*.txt pins, tenshoe.ld, symbol_addrs.txt,
    scripts/*.json bindings, README / DECOMPILED_FUNCTIONS.md;
  * DERIVED build symbols `OLD_rodata`, `OLD_bss`, `OLD_data`, ... (made by
    replace-function-body.py as func_name + section name, pinned in
    undefined_syms) are renamed to `NEW_<sect>` too;
  * file NAMES whose stem token is OLD (INCLUDE_ASM resolves `<dir>/<NAME>.s`,
    src/match_imports/<NAME>.c, scripts/match-bindings-<NAME>[-nm].json) via git mv;
  * expected/**/*.o symbol tables (objdiff matches target symbols BY NAME):
    OLD, OLD.NON_MATCHING and derived OLD_<sect> are renamed in place with the
    metadata-only strtab repoint of scripts/rename-elf-symbol.py (NOT objcopy,
    which rewrites the symtab and renames local section symbols);
  * KERNEL symbols (defined in src/kernel objects) rename only the definition
    side: the kernel runs at link address + 0x400, so every call / %hi-%lo /
    UND reference to kernel symbol X really means the function at X - 0x400.
    Those references keep the OLD spelling (and UND entries in expected/ objects
    keep OLD), and OLD is pinned as an absolute alias in undefined_syms_auto.txt;
  * appends `OLD<TAB>NEW` to renames.tsv (ledger: docs in the monorepo keep
    using the old placeholder names; grep this file to translate).

Refusals (names never reach the ROM: USO Sym tables carry [tag,value,HASH]
of the ORIGINAL names as ROM data, and the ROM is objcopy -O binary of the
link, so symbol strings are not emitted. The only ways a rename could change
bytes are guarded here):
  * OLD inside a C string literal / .ascii(z) (would change data bytes);
  * OLD appearing mangled (`OLD__F...`, C++ objcopy --redefine-sym maps);
  * OLD is a zero-address sentinel (`*_00000000*`, USO import/base placeholders);
  * NEW not a valid identifier / is a C keyword / already a symbol in any
    expected or build object, undefined_syms, symbol_addrs or tenshoe.ld;
  * NEW already used as a CODE token (comments stripped) in a file that
    contains OLD (two meanings would merge inside one TU, e.g. a local
    `#define osSendMesg gl_func_00000000`);
  * OLD defined in objects of more than one src/<segment>/ (ambiguous).
Post-check: every derived pin `OLD_<sect>` that existed in a tracked text file
(undefined_syms_auto.txt etc.) must afterwards exist as `NEW_<sect>` and no
`OLD_<sect>` may remain; otherwise the run fails loudly (a stale derived pin
leaves an undefined symbol and ld segfaults).
After a batch, run scripts/readability-gate.sh (full make + ROM cmp +
verify-blocks + non_matching_objects + report diff by address).
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
rfb = __import__("replace-function-body")

ROOT = Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], cwd=HERE, text=True).strip())
DERIVED = ("rodata", "data", "bss", "sdata", "sbss", "text", "lit4", "lit8")
SKIP_PREFIX = ("episodes/", "tools/", "assets/", "expected/", "landwip/")
SKIP_FILES = {"report.json", "renames.tsv"}
C_KEYWORDS = set("""auto break case char const continue default do double else enum extern float for goto
if int long register return short signed sizeof static struct switch typedef union unsigned void volatile
while class new delete this operator template virtual inline""".split())
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def word_re(name):
    return re.compile(r"(?<![A-Za-z0-9_])" + re.escape(name) + r"(?![A-Za-z0-9_])")


def token_re(old):
    # OLD, OLD.NON_MATCHING (via the '.' boundary) and OLD_<derived section>
    return re.compile(r"(?<![A-Za-z0-9_])" + re.escape(old) +
                      r"(_(?:" + "|".join(DERIVED) + r"))?(?![A-Za-z0-9_])")


def tracked_text_files():
    out = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT).split(b"\0")
    files = []
    for b in out:
        p = b.decode()
        if not p or p.startswith(SKIP_PREFIX) or p in SKIP_FILES:
            continue
        fp = ROOT / p
        if fp.is_symlink() or not fp.is_file():
            continue
        files.append(p)
    return files


_text_cache = {}


def read_text(p):
    if p not in _text_cache:
        raw = (ROOT / p).read_bytes()
        _text_cache[p] = None if b"\0" in raw[:8192] else raw.decode("utf-8", errors="surrogateescape")
    return _text_cache[p]


def strip_comments(path, text):
    if path.endswith((".c", ".h", ".cpp", ".inc", ".ld", ".txt", ".s")):
        text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
        if path.endswith((".c", ".h", ".cpp")):
            text = re.sub(r"//[^\n]*", " ", text)
    if path.endswith((".s", ".inc")) or path == "Makefile" or path.endswith((".mk", ".sh", ".py")):
        text = re.sub(r"(?m)#(?!\s*(?:include|define|if|ifdef|ifndef|else|endif|pragma)\b)[^\n]*", " ", text)
    return text


def object_files():
    objs = list((ROOT / "expected").rglob("*.o"))
    if (ROOT / "build").is_dir():
        objs += [p for p in (ROOT / "build").rglob("*.o")]
    return objs


def elf_symbols(path):
    try:
        elf = rfb.Elf(path.read_bytes())
        st = elf.find_section(".symtab")
    except Exception:
        return []
    stt = elf.sections[st][6]
    out = []
    for _idx, f in elf.iter_symtab(st):
        name = elf.strtab_string(stt, f[0])
        if name:
            out.append((name, f[5] != 0))  # (name, defined)
    return out


class Index:
    def __init__(self):
        self.obj_syms = {}  # path -> [(name, defined)]
        for o in object_files():
            self.obj_syms[o] = elf_symbols(o)
        self.linker_names = set()
        for f in list(ROOT.glob("undefined_*.txt")) + [ROOT / "symbol_addrs.txt", ROOT / "tenshoe.ld"]:
            if f.exists():
                for m in re.finditer(r"(?m)^\s*([A-Za-z_][A-Za-z0-9_.]*)\s*=", strip_comments(f.name, f.read_text(errors="replace"))):
                    self.linker_names.add(m.group(1))
        self.all_names = set(self.linker_names)
        for syms in self.obj_syms.values():
            self.all_names.update(n for n, _ in syms)

    def defining_segments(self, name):
        segs = set()
        for o, syms in self.obj_syms.items():
            if any(n == name and d for n, d in syms):
                rel = o.relative_to(ROOT).parts
                # expected/src/<seg>/x.o | build/[non_matching/]src/<seg>/x.o
                if "src" in rel:
                    i = rel.index("src")
                    if i + 1 < len(rel) - 1:
                        segs.add(rel[i + 1])
        return segs


def scoped_alias_ok(path, text, old, new):
    """True when every CODE occurrence of NEW in this C file sits inside a
    `#define NEW ...` .. `#undef NEW` scope (a TU-local macro alias such as the
    OoT names in game_libs_post.c), and OLD (or a derived OLD_<sect>) never
    occurs inside such a scope. Then renaming OLD -> NEW cannot merge two
    meanings: outside the scopes NEW was unused, inside them OLD was."""
    if not path.endswith((".c", ".cpp", ".h")):
        return False
    to, wn = token_re(old), word_re(new)
    d_re = re.compile(r"#\s*define\s+" + re.escape(new) + r"(?![A-Za-z0-9_])")
    u_re = re.compile(r"#\s*undef\s+" + re.escape(new) + r"(?![A-Za-z0-9_])")
    inside = False
    saw_scope = False
    for line in strip_comments(path, text).splitlines():
        s = line.strip()
        if d_re.match(s):
            if inside:
                return False  # nested/unterminated scope: be conservative
            inside = saw_scope = True
            if to.search(s):
                return False
            continue
        if u_re.match(s):
            if not inside:
                return False
            inside = False
            continue
        if inside:
            if to.search(line):
                return False
        elif wn.search(line):
            return False
    return saw_scope and not inside


def c_definitions(path, name):
    """Function definitions of NAME in a C file, comments stripped and whitespace
    collapsed: from the start of the line holding `NAME(` (not a prototype) to the
    matching closing brace."""
    text = strip_comments(path, read_text(path) or "")
    out = []
    for m in re.finditer(r"(?m)^[^\n;#]*(?<![A-Za-z0-9_])" + re.escape(name) + r"\s*\(", text):
        i = text.find("{", m.end())
        semi = text.find(";", m.end())
        if i < 0 or (0 <= semi < i):
            continue
        depth, j = 0, i
        while j < len(text):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        out.append(" ".join(text[m.start():j + 1].split()))
    return out


def copies_identical(old, host_seg):
    host, copies = [], []
    for p in (ROOT / "src" / host_seg).rglob("*.c"):
        host += c_definitions(str(p.relative_to(ROOT)), old)
    for p in (ROOT / "src" / "match_imports").glob("*.c"):
        copies += c_definitions(str(p.relative_to(ROOT)), old)
    if len(host) != 1:
        return False, f"{len(host)} host definitions"
    if not copies:
        return False, "no match_imports definition found"
    if any(c != host[0] for c in copies):
        return False, "text differs from the host definition"
    return True, ""


def check(old, new, idx, files, pending_new, allow_scoped_alias=False):
    errs, warns = [], []
    if not IDENT.match(new) or new in C_KEYWORDS:
        errs.append(f"NEW {new!r} is not a valid C identifier")
    if old == new:
        errs.append("OLD == NEW")
    if "00000000" in old:
        errs.append(f"{old} is a zero-address sentinel/placeholder name (USO import/base); never rename")
    if new in idx.all_names or new in pending_new:
        errs.append(f"NEW {new} already exists as a symbol (object/undefined_syms/symbol_addrs/ld/batch)")
    for d in DERIVED:
        if f"{new}_{d}" in idx.all_names:
            errs.append(f"derived NEW {new}_{d} already exists")
    known = old in idx.all_names
    if not known:
        errs.append(f"OLD {old} is not a symbol in any expected/build object or linker-symbol file")
    segs = idx.defining_segments(old)
    # src/match_imports/OLD.c is a per-function port (REPLACE_FUNC_BODY donor) of the SAME
    # function defined in its host segment, not a second function with the same name, so a
    # {host, match_imports} pair is not ambiguous (agent-g run 447; the gate verifies the splice).
    if len(segs) == 2 and "match_imports" in segs and (ROOT / "src" / "match_imports" / f"{old}.c").exists():
        segs = segs - {"match_imports"}
    # A match_imports file named after ANOTHER function may carry verbatim context copies
    # of its predecessors (e.g. src/match_imports/sys_fatal.c holds 610F4/611E4/6126C so
    # the spliced function keeps its original alignment). Allowed only when every
    # match_imports definition of OLD is textually identical (comments stripped,
    # whitespace normalized) to the single host definition (agent-b run 454).
    if len(segs) == 2 and "match_imports" in segs:
        host = segs - {"match_imports"}
        same, why = copies_identical(old, next(iter(host)))
        if same:
            segs = host
        else:
            warns.append(f"{old}: match_imports copy is not an exact-same-function copy ({why})")
    if len(segs) > 1:
        errs.append(f"{old} is defined in several segments {sorted(segs)}; rename is ambiguous")
    wr, nr = word_re(old), word_re(new)
    # select files by TOKEN (OLD, OLD.NON_MATCHING, OLD_<sect>), not by the plain
    # word: undefined_syms_auto.txt may pin only the derived OLD_rodata/OLD_bss
    # (agent-c run 444: the pin was missed and ld segfaulted on the undefined symbol).
    tr = token_re(old)
    mangled = re.compile(r"(?<![A-Za-z0-9_])" + re.escape(old) + r"__[A-Za-z0-9]")
    strlit = re.compile(r'"(?:[^"\\\n]|\\.)*"')
    hits = []
    for p in files:
        t = read_text(p)
        if t is None or old not in t or not tr.search(t):
            continue
        hits.append(p)
        if mangled.search(t):
            errs.append(f"{p}: {old} appears in a C++-mangled form ({old}__...); handle by hand")
        if p.endswith((".c", ".h", ".cpp")):
            code = strip_comments(p, t)
            for line in code.splitlines():
                if not tr.search(line):
                    continue
                if re.match(r"\s*(#\s*include|#\s*pragma\s+GLOBAL_ASM|INCLUDE_ASM|INCLUDE_RODATA)", line):
                    continue
                for lit in strlit.findall(line):
                    if tr.search(lit):
                        errs.append(f"{p}: {old} inside a string literal (would change data bytes): {line.strip()[:120]}")
        if p.endswith((".s", ".inc")):
            for line in t.splitlines():
                if re.search(r"\.ascii", line) and tr.search(line):
                    errs.append(f"{p}: {old} inside .ascii data: {line.strip()[:120]}")
        if p.endswith(".md"):
            continue  # prose/tables (DECOMPILED_FUNCTIONS.md "| func_X | osName |" rows): no code context
        code = strip_comments(p, t)
        # NEW=OLD is a post-compile rename spec (donor compiled under its real
        # name, renamed to the placeholder); it becomes a harmless NEW=NEW.
        code = re.sub(r"(?<![A-Za-z0-9_])" + re.escape(new) + "=" + re.escape(old) + r"(?![A-Za-z0-9_])", " ", code)
        # Makefile/linker files: one rule line = one context; C/asm: the whole TU.
        units = code.splitlines() if p in ("Makefile", "tenshoe.ld") or p.endswith(".txt") else [code]
        if any(tr.search(u) and nr.search(u) for u in units):
            if allow_scoped_alias and scoped_alias_ok(p, t, old, new):
                warns.append(f"{p}: NEW {new} only used as a scoped #define/#undef alias; tolerated")
            else:
                errs.append(f"{p}: NEW {new} is already a code token in a file/rule that uses {old}")
    return errs, warns, hits


def plan_file_renames(old, new):
    moves = []
    out = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT).split(b"\0")
    pat = word_re(old)
    for b in out:
        p = b.decode()
        if not p or p.startswith(("episodes/", "expected/")):
            continue
        name = Path(p).name
        stem = name.split(".")[0]
        # whole-token match in the basename, but only when OLD is the stem or a
        # dash-delimited part (match-bindings-OLD-nm.json); never `OLD_pad.s`.
        parts = re.split(r"-", stem)
        if stem == old or old in parts:
            newname = pat.sub(new, name)
            moves.append((p, str(Path(p).with_name(newname))))
    return moves


_ASM_DEF_LINE = re.compile(r"^\s*(glabel|endlabel|alabel|dlabel|jlabel|nonmatching|\.globl|\.global|\.ent|\.end|\.size|\.type)\b")
_C_ASM_LINE = re.compile(r"^\s*(INCLUDE_ASM|INCLUDE_RODATA|GLOBAL_ASM|#\s*pragma\s+GLOBAL_ASM)\b")


def _comment_spans(path, text):
    pats = [r"/\*.*?\*/"]
    if path.endswith((".c", ".h", ".cpp")):
        pats.append(r"//[^\n]*")
    if path.endswith((".s", ".inc")):
        pats.append(r"#[^\n]*")
    return [m.span() for m in re.finditer("|".join(pats), text, flags=re.S)]


def kernel_subn(path, text, tr, new):
    """Rename a KERNEL symbol without rewriting its call/address references.

    The kernel runs at link address + 0x400 (it is loaded at 0x80000400 but
    linked/numbered from 0x80000000), so every `jal X` / `%hi(X)` / C call of a
    kernel symbol X in the source really targets the function at X - 0x400;
    the bytes match only because the symbol at X encodes the right address.
    A rename must therefore move only the DEFINITION side (C definition line,
    INCLUDE_ASM/GLOBAL_ASM argument, glabel/endlabel/nonmatching, Makefile /
    linker / symbol files, comments, docs) and leave references spelled OLD,
    which pin_alias() then pins as an absolute (OLD = its address)."""
    is_s = path.endswith((".s", ".inc"))
    is_c = path.endswith((".c", ".cpp"))  # headers (m2c contexts) declare the definitions: full rename
    if not (is_s or is_c):
        t2, n = tr.subn(lambda m: new + (m.group(1) or ""), text)
        return t2, n, 0
    spans = _comment_spans(path, text)
    out, last, n, kept = [], 0, 0, 0
    for m in tr.finditer(text):
        a = m.start()
        ls = text.rfind("\n", 0, a) + 1
        le = text.find("\n", a)
        line = text[ls:le if le >= 0 else len(text)]
        in_comment = any(s <= a < e for s, e in spans)
        if m.group(1) or in_comment:
            ren = True
        elif is_s:
            ren = bool(_ASM_DEF_LINE.match(line)) or re.match(r"^\s*" + re.escape(m.group(0)) + r":", line) is not None
        else:
            code = line.strip()
            ren = bool(_C_ASM_LINE.match(line)) or (
                re.match(r'^(?:extern\s+"C"\s+)?(?!extern\b|typedef\b|return\b)[A-Za-z_]', line) is not None
                and re.search(re.escape(m.group(0)) + r"\s*\(", line) is not None
                and not code.endswith(";"))
        out.append(text[last:a])
        if ren:
            out.append(new + (m.group(1) or ""))
            n += 1
        else:
            out.append(m.group(0))
            kept += 1
        last = m.end()
    out.append(text[last:])
    return "".join(out), n, kept


def pin_alias(old, new, dry):
    m = re.match(r"^(?:func|D)_([0-9A-Fa-f]{8})$", old)
    addr = None
    if m:
        addr = int(m.group(1), 16)
    else:
        sa = read_text("symbol_addrs.txt")
        mm = re.search(r"(?m)^\s*(?:" + re.escape(new) + "|" + re.escape(old) + r")\s*=\s*(0x[0-9A-Fa-f]+)", sa)
        if mm:
            addr = int(mm.group(1), 16)
    if addr is None:
        sys.exit(f"cannot pin kernel alias {old}: address unknown (fix by hand)")
    us = ROOT / "undefined_syms_auto.txt"
    t = read_text("undefined_syms_auto.txt")  # via the cache: later renames in a batch rewrite from it
    if re.search(r"(?m)^\s*" + re.escape(old) + r"\s*=", t):
        return
    line = (f"{old} = 0x{addr:08X};  /* kernel call/address alias: jal/%hi targets are runtime "
            f"addresses (= link + 0x400), so this is the function 0x400 below; "
            f"the symbol linked at 0x{addr:08X} is now {new} */\n")
    t = t + ("" if t.endswith("\n") else "\n") + line
    _text_cache["undefined_syms_auto.txt"] = t
    if not dry:
        us.write_text(t, encoding="utf-8", errors="surrogateescape")


def derived_tokens(name, files):
    """{NAME_<sect>} spelled anywhere in the tracked text files."""
    pats = {f"{name}_{d}": word_re(f"{name}_{d}") for d in DERIVED}
    found = set()
    for p in files:
        t = read_text(p)
        if t is None or name not in t:
            continue
        found.update(k for k, r in pats.items() if r.search(t))
    return found


def apply(renames, dry, allow_scoped_alias=False):
    idx = Index()
    files = tracked_text_files()
    pending = set()
    moved = {}
    all_errs = []
    plan = []
    for old, new in renames:
        errs, warns, hits = check(old, new, idx, files, pending, allow_scoped_alias)
        for w in warns:
            print(f"  note [{old} -> {new}] {w}")
        pending.add(new)
        if errs:
            all_errs += [f"[{old} -> {new}] {e}" for e in errs]
        plan.append((old, new, hits))
    if all_errs:
        print("REFUSED:\n  " + "\n  ".join(all_errs), file=sys.stderr)
        return 1

    for old, new, hits in plan:
        derived_before = derived_tokens(old, files)
        tr = token_re(old)
        sub = lambda m: new + (m.group(1) or "")
        kernel = "kernel" in idx.defining_segments(old)
        nfiles = 0
        nrefs = 0
        kept = 0
        for p in hits:
            while p in moved:  # an earlier rename in this batch git-mv'd the file
                p = moved[p]
            t = read_text(p)
            if kernel:
                t2, n, k = kernel_subn(p, t, tr, new)
                kept += k
            else:
                t2, n = tr.subn(sub, t)
            if n:
                nfiles += 1
                nrefs += n
                if not dry:
                    (ROOT / p).write_text(t2, encoding="utf-8", errors="surrogateescape")
                _text_cache[p] = t2
        # expected/ objects
        specs_by_obj = {}
        for o, syms in idx.obj_syms.items():
            rel = o.relative_to(ROOT)
            if rel.parts[0] != "expected":
                continue
            # kernel: an UND reference in an object is a jal/address alias (see
            # kernel_subn) and keeps OLD; only the defining object is renamed.
            names = {n for n, d in syms if d or not kernel}
            specs = []
            for cand in [old, old + ".NON_MATCHING"] + [f"{old}_{d}" for d in DERIVED]:
                if cand in names:
                    specs.append(f"{cand}={new}{cand[len(old):]}")
            if specs:
                specs_by_obj[o] = specs
        for o, specs in specs_by_obj.items():
            if not dry:
                subprocess.run([sys.executable, str(HERE / "rename-elf-symbol.py"), str(o)] + specs,
                               check=True, stdout=subprocess.DEVNULL)
        moves = plan_file_renames(old, new)
        for a, b in moves:
            if not dry:
                subprocess.run(["git", "mv", a, b], cwd=ROOT, check=True)
            if a in _text_cache:
                _text_cache[b] = _text_cache.pop(a)
            files = [b if f == a else f for f in files]
            moved[a] = b
        if kernel and kept:
            pin_alias(old, new, dry)
        # every derived pin must have followed (files now reflect the rewrite)
        cur = [moved.get(f, f) for f in files]
        stale = derived_tokens(old, cur)
        missing = {f"{new}{d[len(old):]}" for d in derived_before} - derived_tokens(new, cur)
        if stale or missing:
            sys.exit(f"DERIVED-PIN CHECK FAILED for {old} -> {new}: still spelled {sorted(stale)}, "
                     f"missing {sorted(missing)}" + (" (dry run)" if dry else " (tree is half-renamed; fix by hand)"))
        if derived_before:
            print(f"    derived: {', '.join(sorted(derived_before))} -> {new}_* (all present)")
        print(f"{'[dry] ' if dry else ''}{old} -> {new}: {nrefs} refs in {nfiles} files, "
              f"{len(specs_by_obj)} expected objs, {len(moves)} file moves"
              + (f", {kept} kernel call/address refs kept as the {old} alias" if kept else ""))
        for a, b in moves:
            print(f"    mv {a} -> {b}")
        if not dry:
            led = ROOT / "renames.tsv"
            new_ledger = not led.exists()
            with led.open("a") as fh:
                if new_ledger:
                    fh.write("# old\tnew  (ledger of readability renames; docs/ keep the old names)\n")
                fh.write(f"{old}\t{new}\n")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("old", nargs="?")
    ap.add_argument("new", nargs="?")
    ap.add_argument("--batch", type=Path)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--allow-scoped-alias", action="store_true",
                    help="tolerate NEW already used in a C file only inside #define NEW .. #undef NEW scopes")
    a = ap.parse_args()
    renames = []
    if a.batch:
        for line in a.batch.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                o, n = line.split()[:2]
                renames.append((o, n))
    elif a.old and a.new:
        renames.append((a.old, a.new))
    else:
        ap.error("give OLD NEW or --batch FILE")
    olds = [o for o, _ in renames]
    if len(set(olds)) != len(olds):
        sys.exit("duplicate OLD in batch")
    sys.exit(apply(renames, a.dry_run, a.allow_scoped_alias))


if __name__ == "__main__":
    main()
