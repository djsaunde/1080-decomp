#!/usr/bin/env python3
"""PC port: the module registry's tables (docs/1080_PC_PORT_PLAN.md section 16.5).

    scripts/port-gen-uso.py [--lib <libgame.a>]     # after a full matching make

Writes, from the ROM's USO records and the matching build's names (no ROM bytes):
  port/gen/uso_modules.c   one PortUsoModule per module the port keeps data for: its Data /
                           RoData / Bss sizes, its relocation list and its static initialisers;
  port/gen/uso_blobs.tsv   the module -> extracted section files list that
                           port/tools/gen-uso-blobs.py turns into the blob object at build time
                           (sizes only).

Relocation list: every DataReloc / RoDataReloc R_MIPS_32 entry of the module, resolved to a
host expression: `port_<mod>_<sec> + K` for a Data / RoData / Bss target (K = Sym value + the
word's addend), the function name for a Text target (a vtable or callback slot). port/uso
writes the address into the word (host byte order) each time the module "loads".

Modules: every code USO (has Text), plus every data-only USO a code site or alias references
(port/gen/aliases.ld, port/gen/binds.tsv name `port_<mod>_<sec>`), plus every data-only USO
a kept module's data relocations reach (to a fixed point).
"""
import argparse
import collections
import importlib.util
import os
import re
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
os.chdir(ROOT)
spec = importlib.util.spec_from_file_location("pgb", str(ROOT / "scripts/port-gen-binds.py"))
pgb = importlib.util.module_from_spec(spec)
sys.argv, _argv = [sys.argv[0]], sys.argv
spec.loader.exec_module(pgb)
sys.argv = _argv
npc = pgb.npc

# the 4 C++ static initialisers whose .init_array entry the port drops (plan 13.1, port-noinit):
# they run when their module loads, in Text order
STATIC_INITS = ["app_staticInit_000412E8", "Window_staticInit", "boot_staticInit_00006204",
                "SnowBoard_staticCtor_0000E9FC"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lib", default="/tmp/claude-1000/port-build/libgame.a")
    a = ap.parse_args()
    defined, _ = pgb.port_defined(a.lib)     # (names, dropped data objects) since run 616
    excluded = {r[0] for r in pgb.read_tsv("port/gen/excluded.tsv")}
    # functions of the modules not decompiled yet (INCLUDE_ASM): nothing defines them on the host
    # until their C lands, so their slots stay 0 (the blobs and relocations are otherwise complete)
    undecomp = {r[0] for r in pgb.read_tsv("port/gen/excluded.tsv") if "include_asm" in r[-1]}
    excluded -= undecomp
    rom = npc.Rom()
    rt = pgb.RomTargets(rom)
    used = set()
    for path in ("port/gen/aliases.ld", "port/gen/binds.tsv"):
        if os.path.exists(path):
            used |= set(re.findall(r"\bport_(\w+?)_(?:data|rodata|bss)\b", open(path).read()))
    # XDATA(tok, port_<mod>_<sec>, off) sites in the source (scripts/name-data-sites.py)
    import glob
    for path in glob.glob("src/**/*.c*", recursive=True):
        t = open(path, errors="replace").read()
        if "XDATA" in t:
            used |= set(re.findall(r"\bXDATA\s*\(\s*\w+\s*,\s*port_(\w+?)_(?:data|rodata|bss)\b", t))
    mods = [m for m in sorted(rom.mods, key=lambda m: m.id)
            if ("Text" in m.secs or m.short in used) and
            (any(s in m.secs for s in ("Data", "RoData")) or m.bss_size)]
    keep = {m.short for m in mods}
    # plus every data-only USO a kept module's Data / RoData words point into (bootup's course
    # table -> bg4tex.uso's wall textures, plan 18.11), to a fixed point
    grow = True
    while grow:
        grow = False
        for md in list(mods):
            for sec in ("Data", "RoData"):
                for f1, off, _ in md.relocs(sec):
                    t = rt.raw(md, f1 >> 4) if f1 & 7 == 4 else None
                    if t is None or t[0].short in keep or t[1] == "Text":
                        continue
                    ex = t[0]
                    if any(s in ex.secs for s in ("Data", "RoData")) or ex.bss_size:
                        keep.add(ex.short)
                        mods.append(ex)
                        grow = True
    mods.sort(key=lambda m: m.id)
    stats = collections.Counter()
    names = set()
    out = ["/* generated by scripts/port-gen-uso.py -- do not edit.  Plan section 16.5. */",
           '#include "port_uso.h"', ""]
    body = []
    table = []
    tsv = ["# generated by scripts/port-gen-uso.py: module\tfile\tsection\tsize"]
    for md in mods:
        secs = {s: len(md.secs[s]) for s in ("Data", "RoData") if s in md.secs}
        for s, n in secs.items():
            tsv.append("%s\t%s\t%s\t%d" % (md.short, md.name, s, n))
        if md.bss_size:
            tsv.append("%s\t%s\tBss\t%d" % (md.short, md.name, md.bss_size))
        rel = {}
        for sec in ("Data", "RoData"):
            ents = []
            for f1, off, _ in md.relocs(sec):
                typ, idx = f1 & 7, f1 >> 4
                if typ != 4:
                    stats["reloc type %d (not a word)" % typ] += 1
                    continue
                t = rt.raw(md, idx)
                if t is None:
                    stats["unresolved Sym"] += 1
                    ents.append((off, "0", "unresolved sym %d" % idx))
                    continue
                ex, tsec, v = t
                k = struct.unpack_from(">I", md.secs[sec], off)[0]
                if tsec == "Text":
                    nm = ex.name_text((v + k) & 0xFFFFFFFF)
                    if nm in undecomp:
                        ents.append((off, "0", "Text target %s:%s (not decompiled yet)" % (ex.short, nm)))
                        stats["Text target in a module not decompiled yet"] += 1
                    elif nm in defined or nm in excluded:
                        names.add(nm)
                        ents.append((off, "(void *)%s" % nm, None))
                        stats["Text target"] += 1
                    elif re.fullmatch(r"\w+\+0x[0-9A-F]+", nm) and not nm.startswith("Text+"):
                        # a code label inside a function: the ROM's switch jump tables, which
                        # the host code (its own tables) never reads
                        ents.append((off, "0", "jump table %s" % nm))
                        stats["Text target: jump-table label (unused on the host)"] += 1
                    else:
                        ents.append((off, "0", "Text target %s:%s" % (ex.short, nm)))
                        stats["Text target not in the port"] += 1
                    continue
                if ex.short not in keep:
                    ents.append((off, "0", "%s %s module not kept" % (ex.short, tsec)))
                    stats["target module not kept"] += 1
                    continue
                ents.append((off, "%s + 0x%X" % (pgb.blob_sym(ex.short, tsec), (v + k) & 0xFFFFFFFF), None))
                stats["%s target" % tsec] += 1
            if ents:
                rel[sec] = ents
                body.append("static const PortUsoReloc %s_rel[%d] = {" % (pgb.blob_sym(md.short, sec), len(ents)))
                for off, expr, why in ents:
                    body.append("    {0x%X, %s}," % (off, expr) + (" /* %s */" % why if why else ""))
                body.append("};")
        inits = sorted((v, nm) for v, sz, nm in md.funcs if nm in STATIC_INITS)
        if inits:
            names.update(nm for _, nm in inits)
            body.append("static void (*const port_%s_inits[])(void) = {%s, 0};" % (
                md.short, ", ".join("(void (*)(void))%s" % nm for _, nm in inits)))

        def ref(sec, kind):
            return pgb.blob_sym(md.short, sec) + kind if (sec in secs or (sec == "Bss" and md.bss_size)) else "0"
        table.append("    {\"%s\", %d, %s, %s, %d, %s, %s, %d, %s, %d, %s, %d, %s, %d, %s}," % (
            md.name, md.id,
            ref("Data", ""), ref("Data", "_init"), secs.get("Data", 0),
            ref("RoData", ""), ref("RoData", "_init"), secs.get("RoData", 0),
            ref("Bss", ""), md.bss_size,
            ("%s_rel" % pgb.blob_sym(md.short, "Data")) if "Data" in rel else "0", len(rel.get("Data", ())),
            ("%s_rel" % pgb.blob_sym(md.short, "RoData")) if "RoData" in rel else "0", len(rel.get("RoData", ())),
            ("port_%s_inits" % md.short) if inits else "0"))
    for md in mods:
        for s in ("Data", "RoData"):
            if s in md.secs:
                out.append("extern char %s[], %s_init[];" % (pgb.blob_sym(md.short, s), pgb.blob_sym(md.short, s)))
        if md.bss_size:
            out.append("extern char %s[];" % pgb.blob_sym(md.short, "Bss"))
    out.append("")
    for nm in sorted(names):
        out.append("extern char %s[];" % nm)
    out.append("")
    out += body
    out.append("")
    out.append("const PortUsoModule port_uso_modules[] = {")
    out += table
    out.append("};")
    out.append("const int port_uso_nmodules = %d;" % len(table))
    Path("port/gen/uso_modules.c").write_text("\n".join(out) + "\n")
    Path("port/gen/uso_blobs.tsv").write_text("\n".join(tsv) + "\n")
    print("modules %d (code %d); relocations: %s" % (
        len(mods), sum(1 for m in mods if "Text" in m.secs), dict(stats)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
